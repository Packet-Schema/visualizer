import { readFileSync, writeFileSync } from "fs";
import { resolve } from "path";

function generateFont(
  variant: "og" | "export",
  filename: string,
  exportName: string,
) {
  const fontPath = resolve(
    process.cwd(),
    "node_modules",
    "@fontsource",
    "line-seed-jp",
    "files",
    filename,
  );

  try {
    const buffer = readFileSync(fontPath);
    const base64 = buffer.toString("base64");
    const outputPath = resolve(process.cwd(), "lib", "og-font.ts");

    const variableName =
      variant === "og" ? "LINE_SEED_JP_OG_FONT_B64" : "LINE_SEED_JP_EXPORT_FONT_B64";
    const variableExport =
      variant === "og" ? "OG_FONT_BUFFER" : "EXPORT_FONT_BUFFER";

    let content: string;
    if (variant === "og") {
      content = `// Auto-generated by scripts/generate-og-font.ts — do not edit
const ${variableName} = "${base64}";
const ogFontBuffer = Buffer.from(${variableName}, "base64");
export const OG_FONT_BUFFER: ArrayBuffer = ogFontBuffer.buffer.slice(ogFontBuffer.byteOffset, ogFontBuffer.byteOffset + ogFontBuffer.byteLength);

const EXPORT_FONT_B64 = "${base64}";
const exportFontBuffer = Buffer.from(EXPORT_FONT_B64, "base64");
export const EXPORT_FONT_BUFFER: ArrayBuffer = exportFontBuffer.buffer.slice(exportFontBuffer.byteOffset, exportFontBuffer.byteOffset + exportFontBuffer.byteLength);
`;
    } else {
      // This will be appended to the file
      return {
        buffer,
        base64,
      };
    }

    writeFileSync(outputPath, content);
    console.log(
      `✓ og-font.ts generated (OG: ${(buffer.length / 1024).toFixed(1)} KB)`,
    );
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(`Failed to generate font (${variant}):`);
    console.error(`  Path attempted: ${fontPath}`);
    console.error(`  Error: ${message}`);

    if (message.includes("ENOENT")) {
      console.error(`  → Missing dependency. Run: npm ci`);
    } else if (message.includes("EACCES")) {
      console.error(`  → Permission denied. Check file permissions.`);
    } else {
      console.error(`  Ensure @fontsource/line-seed-jp is installed: npm ci`);
    }

    process.exit(1);
  }
}

// OG用フォント: ASCII + 基本文字のみ (4.9 KB)
const ogBuffer = readFileSync(
  resolve(
    process.cwd(),
    "node_modules",
    "@fontsource",
    "line-seed-jp",
    "files",
    "line-seed-jp-0-400-normal.woff",
  ),
);
const ogBase64 = ogBuffer.toString("base64");

// Export用フォント: 日本語フル対応 (1.8+ MB)
const exportBuffer = readFileSync(
  resolve(
    process.cwd(),
    "node_modules",
    "@fontsource",
    "line-seed-jp",
    "files",
    "line-seed-jp-japanese-400-normal.woff",
  ),
);
const exportBase64 = exportBuffer.toString("base64");

const content = `// Auto-generated by scripts/generate-og-font.ts — do not edit
const OG_FONT_B64 = "${ogBase64}";
const ogFontBuffer = Buffer.from(OG_FONT_B64, "base64");
export const OG_FONT_BUFFER: ArrayBuffer = ogFontBuffer.buffer.slice(ogFontBuffer.byteOffset, ogFontBuffer.byteOffset + ogFontBuffer.byteLength);

const EXPORT_FONT_B64 = "${exportBase64}";
const exportFontBuffer = Buffer.from(EXPORT_FONT_B64, "base64");
export const EXPORT_FONT_BUFFER: ArrayBuffer = exportFontBuffer.buffer.slice(exportFontBuffer.byteOffset, exportFontBuffer.byteOffset + exportFontBuffer.byteLength);
`;

try {
  const outputPath = resolve(process.cwd(), "lib", "og-font.ts");
  writeFileSync(outputPath, content);
  console.log(
    `✓ og-font.ts generated (OG: ${(ogBuffer.length / 1024).toFixed(1)} KB, Export: ${(exportBuffer.length / 1024).toFixed(1)} KB)`,
  );
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`Failed to generate og-font.ts:`);
  console.error(`  Error: ${message}`);
  process.exit(1);
}
