// Build-time code generator. Two jobs:
//
// 1. PSDL editor schema — emit `psdl.schema.generated.ts`, a TS module wrapping
//    the canonical PSDL 0.5 JSON Schema shipped by `@packet-schema/core`
//    (`schemas/psdl-0.5.yaml`) so the in-browser editor can Ajv-lint source
//    without importing a file from outside the web bundle.
//
// 2. Lazy-load preset artifacts — split `@packet-schema/presets` (184 presets,
//    ~960 KB) out of the client bundle:
//      * `public/presets/<key>.json`            — one rowBits-adapted Packet per
//        preset, fetched on demand when the user selects it.
//      * `lib/psdl/preset-index.generated.ts`   — a tiny `{ key: { name } }` map
//        bundled into the client for the preset picker (key → display name).
//    Server routes (`app/page.tsx`, `app/api/og`) still import the full set via
//    `lib/psdl/presets.server.ts`; only the client goes through the index +
//    per-preset fetch.
//
// All generated files are gitignored; recreated on every `npm run
// build:presets`, wired into `prebuild` / `pretest` so neither `next build`
// nor `vitest` runs against stale artifacts.

import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { parse as parseYaml } from "yaml";

import { applyPresetPatches } from "../lib/psdl/preset-patches";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const REPO_ROOT = resolve(__dirname, "..", "..");
const WEB_ROOT = join(REPO_ROOT, "web");
// Canonical PSDL 0.5 schema ships inside @packet-schema/core. Resolve it from
// the web/ node_modules so this works regardless of the repo's hoisting.
const SCHEMA_PATH = join(
  WEB_ROOT,
  "node_modules",
  "@packet-schema",
  "core",
  "schemas",
  "psdl-0.5.yaml",
);
const SCHEMA_OUT_PATH = join(
  WEB_ROOT,
  "lib",
  "psdl",
  "psdl.schema.generated.ts",
);
// Per-preset JSON served as static assets and fetched on demand by the client.
const PRESETS_OUT_DIR = join(WEB_ROOT, "public", "presets");
// Tiny key → metadata map bundled into the client for the picker.
const INDEX_OUT_PATH = join(
  WEB_ROOT,
  "lib",
  "psdl",
  "preset-index.generated.ts",
);

/**
 * Fill the visualizer's `rowBits` invariant from `rendererHints.rowBits` (or a
 * 32-bit default) and apply visualizer-owned preset patches. MUST stay in sync
 * with `adaptPreset` in `lib/psdl/presets.server.ts` so the JSON served to the
 * client matches what the server computes.
 */
function adaptPreset(
  key: string,
  p: Record<string, unknown>,
): Record<string, unknown> {
  const rendererHints = p.rendererHints as { rowBits?: number } | undefined;
  const rowBits =
    (p.rowBits as number | undefined) ?? rendererHints?.rowBits ?? 32;
  return applyPresetPatches(key, { ...p, rowBits });
}

function writeSchema(): void {
  const schema = parseYaml(readFileSync(SCHEMA_PATH, "utf8"));
  const schemaSrc =
    "// AUTO-GENERATED by scripts/build-presets.ts. DO NOT EDIT.\n" +
    "// Source: @packet-schema/core schemas/psdl-0.5.yaml — keep in lock-step.\n" +
    "// eslint-disable\n" +
    "/* prettier-ignore */\n" +
    "export const PSDL_JSON_SCHEMA = " +
    JSON.stringify(schema, null, 2) +
    " as const;\n";
  mkdirSync(dirname(SCHEMA_OUT_PATH), { recursive: true });
  writeFileSync(SCHEMA_OUT_PATH, schemaSrc, "utf8");
  console.log(`Wrote ${relative(REPO_ROOT, SCHEMA_OUT_PATH)}.`);
}

async function writePresetArtifacts(): Promise<void> {
  // `@packet-schema/presets` exposes only an ESM ("import") export condition,
  // so resolve it via dynamic import (tsx loads this script through the CJS
  // loader, where a static bare import of an import-only package fails).
  const { PRESETS } = (await import("@packet-schema/presets")) as {
    PRESETS: Record<string, Record<string, unknown>>;
  };

  // Start from a clean per-preset dir so a removed/renamed preset upstream
  // doesn't leave a stale JSON behind.
  rmSync(PRESETS_OUT_DIR, { recursive: true, force: true });
  mkdirSync(PRESETS_OUT_DIR, { recursive: true });

  const index: Record<string, { name: string }> = {};
  let count = 0;
  for (const [key, preset] of Object.entries(PRESETS)) {
    const adapted = adaptPreset(key, preset);
    writeFileSync(
      join(PRESETS_OUT_DIR, `${key}.json`),
      JSON.stringify(adapted),
      "utf8",
    );
    index[key] = { name: String(adapted.name ?? key) };
    count++;
  }

  const indexSrc =
    "// AUTO-GENERATED by scripts/build-presets.ts. DO NOT EDIT.\n" +
    "// Lightweight preset index (key → display name) for the picker. The full\n" +
    "// preset body is fetched on demand from `/presets/<key>.json`.\n" +
    "// eslint-disable\n" +
    "/* prettier-ignore */\n" +
    "export const PRESET_INDEX: Record<string, { name: string }> = " +
    JSON.stringify(index, null, 2) +
    ";\n\nexport const PRESET_KEYS: string[] = Object.keys(PRESET_INDEX);\n";
  mkdirSync(dirname(INDEX_OUT_PATH), { recursive: true });
  writeFileSync(INDEX_OUT_PATH, indexSrc, "utf8");

  console.log(
    `Wrote ${count} presets to ${relative(REPO_ROOT, PRESETS_OUT_DIR)}/ ` +
      `and ${relative(REPO_ROOT, INDEX_OUT_PATH)}.`,
  );
}

async function main(): Promise<void> {
  writeSchema();
  await writePresetArtifacts();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
